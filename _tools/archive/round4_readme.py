def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read().replace("\r\n", "\n")


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main():
    errors = []

    for fn, desc in DESC:
        p = os.path.join(SRC, fn)
        txt = read(p)
        lines = txt.split("\n")
        changed = False
        for i, line in enumerate(lines):
            if line.startswith("desc: "):
                lines[i] = "desc: " + desc
                changed = True
                break
        if not changed:
            errors.append("%s: 未找到 desc 行" % fn)
            continue
        write(p, "\n".join(lines))

    p = README
    txt = read(p)
    for old, new in README_BLOCKS:
        n = txt.count(old)
        if n != 1:
            errors.append("README: 命中 %d 次 -> %r" % (n, old[:40]))
            continue
        txt = txt.replace(old, new)
    write(p, txt)

    for e in errors:
        print("ERROR " + e)
    print("README 与分类描述已同步：%d 个分类描述，%d 处表格。" % (len(DESC), len(README_BLOCKS)))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
