def main():
    changed = 0
    skipped = []
    for fname, old, new in R:
        if new == "SKIP":
            continue
        path = os.path.join(SRC, fname)
        with open(path, encoding="utf-8") as f:
            text = f.read()
        n = text.count(old)
        if n != 1:
            skipped.append((fname, old[:44], n))
            continue
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(text.replace(old, new))
        changed += 1
    print(f"applied {changed}/{sum(1 for _, _, n in R if n != 'SKIP')}")
    for fname, old, n in skipped:
        print(f"SKIP hit={n} {fname} :: {old}")
    return 1 if skipped else 0


if __name__ == "__main__":
    sys.exit(main())
