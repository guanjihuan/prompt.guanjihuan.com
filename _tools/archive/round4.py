def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read().replace("\r\n", "\n")


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main():
    cache = {}
    errors = []
    for fn, old, new in REPLACE:
        p = os.path.join(SRC, fn)
        txt = cache.get(fn) or read(p)
        n = txt.count(old)
        if n != 1:
            errors.append("REPLACE %s: 命中 %d 次 -> %r" % (fn, n, old[:30]))
            continue
        cache[fn] = txt.replace(old, new)

    for fn, block in REMOVE:
        p = os.path.join(SRC, fn)
        txt = cache.get(fn) or read(p)
        n = txt.count(block)
        if n != 1:
            errors.append("REMOVE %s: 命中 %d 次 -> %r" % (fn, n, block[:30]))
            continue
        cache[fn] = txt.replace(block, "")

    for fn, title, tags, short, body in ADD:
        p = os.path.join(SRC, fn)
        txt = cache.get(fn) or read(p)
        pid = "p-" + hashlib.sha1(title.encode("utf-8")).hexdigest()[:16]
        if ("<!-- id: %s -->" % pid) in txt:
            errors.append("ADD %s: id 重复 %s" % (fn, pid))
            continue
        block = ("## %s\n<!-- id: %s -->\n<!-- t: %s -->\n<!-- s: %s -->\n\n%s\n"
                 % (title, pid, tags, short, body))
        if not txt.endswith("\n"):
            txt += "\n"
        cache[fn] = txt + ("\n" if not txt.endswith("\n\n") else "") + block

    for fn, txt in cache.items():
        write(os.path.join(SRC, fn), txt)

    for e in errors:
        print("ERROR " + e)
    print("完成：改写 %d 处，删除 %d 条，新增 %d 条。" % (len(REPLACE), len(REMOVE), len(ADD)))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
