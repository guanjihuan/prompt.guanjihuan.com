def main():
    hits = 0
    for fn in sorted(os.listdir(SRC)):
        if not fn.endswith(".md"):
            continue
        path = os.path.join(SRC, fn)
        lines = open(path, encoding="utf-8").read().split("\n")
        out, cur, buf = [], None, []
        entries = []
        for l in lines:
            m = T.match(l)
            if m:
                if cur:
                    entries.append((cur, buf))
                cur, buf = m.group(1), []
            elif cur is not None:
                buf.append(l)
            else:
                out.append(l)
        if cur:
            entries.append((cur, buf))

        changed = False
        for title, body in entries:
            key = (fn, title)
            if key in R:
                changed = True
                hits += 1
                meta = [l for l in body if l.strip().startswith("<!--")]
                out.append("## " + title)
                out.extend(meta)
                out.append(R[key])
                out.append("")
                print("  改写  %-16s %s" % (fn[:14], title))
                continue
            out.append("## " + title)
            out.extend(body)

        if changed:
            text = re.sub(r"\n{3,}", "\n\n", "\n".join(out)).rstrip("\n") + "\n"
            open(path, "w", encoding="utf-8").write(text)
    print("共改写 %d 条" % hits)


if __name__ == "__main__":
    main()
