def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read().replace("\r\n", "\n")


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main():
    errors = []
    cache = {}

    for fn, title, tags, short, body in ADD:
        p = os.path.join(SRC, fn)
        txt = cache.get(fn) if fn in cache else read(p)
        pid = "p-" + hashlib.sha1(title.encode("utf-8")).hexdigest()[:16]
        if ("<!-- id: %s -->" % pid) in txt:
            errors.append("ADD %s: id 重复 %s" % (fn, pid))
            continue
        if ("## %s\n" % title) in txt:
            errors.append("ADD %s: 标题重复 %s" % (fn, title))
            continue
        block = "## %s\n<!-- id: %s -->\n<!-- t: %s -->\n<!-- s: %s -->\n\n%s\n" % (
            title, pid, tags, short, body)
        if not txt.endswith("\n"):
            txt += "\n"
        txt = txt + ("\n" if not txt.endswith("\n\n") else "") + block
        cache[fn] = txt

    for fn, desc in DESC:
        p = os.path.join(SRC, fn)
        txt = cache.get(fn) if fn in cache else read(p)
        lines = txt.split("\n")
        for i, line in enumerate(lines):
            if line.startswith("desc: "):
                lines[i] = "desc: " + desc
                break
        else:
            errors.append("%s: 未找到 desc 行" % fn)
            continue
        cache[fn] = "\n".join(lines)

    for fn, txt in cache.items():
        write(os.path.join(SRC, fn), txt)

    for e in errors:
        print("ERROR " + e)
    print("新增 %d 条，同步 %d 个分类描述。" % (len(ADD), len(DESC)))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
