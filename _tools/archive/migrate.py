FRONT_RE = re.compile(r"^---\s*$")


def parse(path):
    raw = open(path, encoding="utf-8").read().replace("\r\n", "\n")
    lines = raw.split("\n")
    meta = {}
    i = 1
    while i < len(lines) and not FRONT_RE.match(lines[i]):
        if ":" in lines[i]:
            k, v = lines[i].split(":", 1)
            meta[k.strip()] = v.strip()
        i += 1
    return meta, lines[i + 1:]


def main():
    files = sorted(f for f in os.listdir(SRC) if f.endswith(".md"))
    changed = 0
    for fn in files:
        path = os.path.join(SRC, fn)
        meta, body = parse(path)
        cid = meta.get("id")
        if cid not in CAT:
            print("!! 未知分类 id:", cid, fn)
            continue
        newfile, name, icon, order, section, desc = CAT[cid]

        out = []
        renamed = 0
        for line in body:
            m = re.match(r"^##\s+(.*\S)\s*$", line)
            if m:
                old = m.group(1)
                if old in TITLES and TITLES[old] != old:
                    line = "## " + TITLES[old]
                    renamed += 1
            out.append(line)

        head = [
            "---",
            "id: %s" % cid,
            "name: %s" % name,
            'icon: "%s"' % icon,
            "desc: %s" % desc,
            "section: %s" % section,
            "order: %d" % order,
            "---",
            "",
        ]
        newtext = "\n".join(head + out).rstrip("\n") + "\n"
        open(os.path.join(SRC, newfile), "w", encoding="utf-8").write(newtext)
        if newfile != fn:
            os.remove(path)
        changed += 1
        if renamed:
            print("  %-20s 改名 %d 处" % (cid, renamed))
    print("已处理 %d 个分类文件" % changed)


if __name__ == "__main__":
    main()
