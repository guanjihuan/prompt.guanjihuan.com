def main():
    added = fixed = 0
    for fn in sorted(os.listdir(SRC)):
        if not fn.endswith(".md"):
            continue
        path = os.path.join(SRC, fn)
        lines = open(path, encoding="utf-8").read().split("\n")
        out = []
        cur = None
        i = 0
        while i < len(lines):
            l = lines[i]
            m = T.match(l)
            if m:
                title = m.group(1)
                out.append(l)
                # 找标签行与说明行
                j = i + 1
                tag_line = None
                note_line = None
                while j < len(lines) and lines[j].strip().startswith("<!--"):
                    if lines[j].lstrip().startswith("<!-- t:"):
                        tag_line = lines[j]
                    else:
                        note_line = lines[j]
                    j += 1
                out.extend(lines[i + 1:j])
                if title in FIX and note_line is not None:
                    note_line = "<!-- n: %s -->" % FIX[title]
                    fixed += 1
                elif note_line is None and title in NOTE:
                    note_line = "<!-- n: %s -->" % NOTE[title]
                    added += 1
                if note_line is not None:
                    out.append(note_line)
                i = j
                cur = title
                continue
            out.append(l)
            i += 1
        text = re.sub(r"\n{3,}", "\n\n", "\n".join(out)).rstrip("\n") + "\n"
        open(path, "w", encoding="utf-8").write(text)
    print("补说明 %d 条，修正 %d 条" % (added, fixed))


if __name__ == "__main__":
    main()
