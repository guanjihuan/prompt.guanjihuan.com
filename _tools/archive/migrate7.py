def main():
    added = 0
    missing = []
    for fn in sorted(os.listdir(SRC)):
        if not fn.endswith(".md"):
            continue
        path = os.path.join(SRC, fn)
        lines = open(path, encoding="utf-8").read().split("\n")
        out = []
        cur = None
        i = 0
        while i < len(lines):
            l = lines[i]
            m = T.match(l)
            if m:
                title = m.group(1)
                out.append(l)
                j = i + 1
                meta = []
                while j < len(lines) and lines[j].strip().startswith("<!--"):
                    meta.append(lines[j])
                    j += 1
                newmeta = []
                for mm in meta:
                    if mm.lstrip().startswith("<!-- n:"):
                        if title in SHORT:
                            newmeta.append("<!-- s: %s -->" % SHORT[title])
                            added += 1
                        else:
                            missing.append((fn, title))
                    else:
                        newmeta.append(mm)
                out.extend(newmeta)
                i = j
                cur = title
                continue
            out.append(l)
            i += 1
        text = re.sub(r"\n{3,}", "\n\n", "\n".join(out)).rstrip("\n") + "\n"
        open(path, "w", encoding="utf-8").write(text)

    print("写入简洁表达 %d 条" % added)
    if missing:
        print("缺少映射 %d 条：" % len(missing))
        for f, t in missing:
            print("   ", f, t)


if __name__ == "__main__":
    main()
